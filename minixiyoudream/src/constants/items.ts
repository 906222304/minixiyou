export function getGemTemplates(): ItemTemplate[] {
  return GEM_TEMPLATES;
}

/** 获取指定类型和等级的宝石模板 */
export function getGemTemplate(type: GemType, level: number): ItemTemplate | undefined {
  return ITEM_TEMPLATES[`gem_${type}_${level}`];
}

/** 获取指定类型的所有宝石模板 */
export function getGemTemplatesByType(type: GemType): ItemTemplate[] {
  return GEM_TEMPLATES.filter(t => t.gemType === type);
}

/** 获取指定等级的所有宝石模板 */
export function getGemTemplatesByLevel(level: number): ItemTemplate[] {
  return GEM_TEMPLATES.filter(t => t.gemLevel === level);
}

/** 按类型获取物品模板 */
export function getItemTemplatesByType(type: ItemTemplate['type']): ItemTemplate[] {
  switch (type) {
    case 'consumable':
      return CONSUMABLE_TEMPLATES;
    case 'quest':
      return QUEST_TEMPLATES;
    case 'material':
      return MATERIAL_TEMPLATES;
    case 'gem':
      return GEM_TEMPLATES;
    case 'special':
      return SPECIAL_TEMPLATES;
    default:
      return [];
  }
}

/** 获取指定任务相关的物品 */
export function getQuestItemsByQuestId(questId: string): ItemTemplate[] {
  return QUEST_TEMPLATES.filter(item => item.questId === questId);
}
