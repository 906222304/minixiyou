/** 获取宠物模板 */
export function getPetTemplate(id: string): PetTemplate | undefined {
  return PET_TEMPLATES[id];
}

/** 获取所有宠物模板 */
export function getAllPetTemplates(): PetTemplate[] {
  return Object.values(PET_TEMPLATES);
}

/** 获取地图可捕捉的宠物 */
export function getCapturablePets(mapId: string): PetTemplate[] {
  return Object.values(PET_TEMPLATES).filter(t =>
    t.captureLocations.includes(mapId)
  );
}

/** 获取指定类型的宠物 */
export function getPetsByType(type: string): PetTemplate[] {
  return Object.values(PET_TEMPLATES).filter(t => t.type === type);
}

/** 获取指定品质的宠物 */
export function getPetsByRarity(rarity: string): PetTemplate[] {
  return Object.values(PET_TEMPLATES).filter(t => t.baseRarity === rarity);
}

/** 获取可进化的宠物 */
export function getEvolvablePets(): PetTemplate[] {
  return Object.values(PET_TEMPLATES).filter(t => t.evolution);
}

