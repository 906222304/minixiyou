/** 生成随机资质 */
function randomAptitude(prng: () => number): PetAptitude {
  return {
    attack: 0.8 + prng() * 0.7,
    defense: 0.8 + prng() * 0.7,
    magic: 0.8 + prng() * 0.7,
    speed: 0.8 + prng() * 0.7,
    hp: 0.8 + prng() * 0.7,
    mp: 0.8 + prng() * 0.7,
  };
}

